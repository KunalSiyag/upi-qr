export function freelanceDefaults(field: keyof Pick<
  FreelanceCopy,
  | "defaultPaymentTerms"
  | "defaultRevision"
  | "defaultReview"
  | "defaultIp"
  | "defaultLateFee"
  | "defaultKillFee"
>): string[] {
  return Object.values(FREELANCE_COPY).map((copy) => copy[field]);
}

export function formatClientSignatory(copy: FreelanceCopy, clientName: string) {
  if (copy.clientSignPrefix === "की ओर से" || copy.clientSignPrefix === "तर्फे") {
    return `${clientName} ${copy.clientSignPrefix}`;
  }
  if (copy.clientSignPrefix === "சார்பாக" || copy.clientSignPrefix === "తరఫున") {
    return `${clientName} ${copy.clientSignPrefix}`;
  }
  return `${copy.clientSignPrefix} ${clientName}`;
}

export function formatFreelancerSignatory(copy: FreelanceCopy, freelancerName: string) {
  return `${freelancerName} ${copy.freelancerSignSuffix}`;
}
