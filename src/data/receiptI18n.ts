export function receiptModeLabel(copy: ReceiptCopy, mode: string) {
  switch (mode) {
    case "Cash":
      return copy.modeCash;
    case "Card":
      return copy.modeCard;
    case "Bank Transfer":
      return copy.modeBank;
    case "Cheque":
      return copy.modeCheque;
    default:
      return copy.modeUpi;
  }
}
