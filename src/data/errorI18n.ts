export function localizeErrorCode(lang: SiteLang, item: { code: string; title: string; cause: string; actionStep: string; merchantNote: string; refundTime: string }) {
  if (lang === "en") return item;
  const overlay = ERROR_CODE_I18N[lang][item.code];
  if (!overlay) return item;
  return { ...item, ...overlay };
}

