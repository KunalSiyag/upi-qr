export function invoiceDocTitle(templateTitle: string, copy: InvoiceCopy) {
  const key = templateTitle.toLowerCase();
  if (key.includes("vat")) return copy.vatInvoice;
  if (key.includes("tax")) return copy.taxInvoice;
  return copy.invoice;
}
