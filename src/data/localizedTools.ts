export function getLocalizedTool(slug: string) {
  return LOCALIZED_TOOLS.find((item) => item.slug === slug);
}

export function getLocalizedToolCopy(tool: LocalizedTool, lang: SupportedToolLanguage): LocalizedToolCopy {
  const raw = tool.copy[lang];
  const title = raw.title.length >= 20 ? raw.title : `${raw.title} | Pro UPI QR`;
  const description = raw.description.length >= 70
    ? raw.description
    : `${raw.description} ${raw.intro}`.slice(0, 160);
  return { ...raw, title, description };
}

export const localizedToolSlugs = LOCALIZED_TOOLS.map((item) => item.slug);
